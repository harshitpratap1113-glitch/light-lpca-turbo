"""
Executive Report Synthesizer (Markdown + Interactive HTML + Structured JSON).
Fulfills deep-research-skill Roadmap #3 while preserving zero-hallucination evidence guarantees.
"""

from __future__ import annotations

import html
from dataclasses import dataclass
from datetime import datetime
from typing import Dict, List

from .auditor import AuditResult
from .search_and_scrape import ScrapedPage


@dataclass
class ResearchReport:
    topic: str
    markdown_content: str
    confidence_score: float
    verified_claim_count: int
    citation_count: int
    generated_at: str
    elapsed_ms: float = 0.0
    cache_hits: int = 0
    has_evidence: bool = True
    html_content: str = ""


class ResearchReportSynthesizer:
    """Compiles audited findings into Markdown and sleek dark-mode HTML reports."""

    def synthesize(
        self,
        topic: str,
        audit_result: AuditResult,
        pages: List[ScrapedPage],
        elapsed_ms: float = 0.0,
        cache_hits: int = 0,
    ) -> ResearchReport:
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        url_to_citation: Dict[str, int] = {url: idx for idx, url in audit_result.citation_index.items()}

        sections: List[str] = [
            f"# Deep Research Report: {topic.title()}\n",
            f"**Generated by LIGHT-LPCA Turbo v2.0** | *{now_str}* | Elapsed: `{elapsed_ms:.1f} ms` (Cache hits: `{cache_hits}`)",
        ]

        if audit_result.has_evidence:
            score_line = f"> **Anti-Hallucination Confidence Score: {audit_result.overall_confidence}%**  \n"
        else:
            score_line = (
                "> **Anti-Hallucination Confidence Score: N/A** "
                "*(no sources could be retrieved - score not measurable)*  \n"
            )
        sections.append(
            f"{score_line}"
            f"> **Total Pages Analyzed:** {audit_result.total_pages_scraped} | "
            f"**Verified Claims:** {len(audit_result.verified_claims)} | "
            f"**Unique Sources:** {len(audit_result.citation_index)}"
        )

        sections.append("## Executive Summary\n")
        if audit_result.has_evidence:
            verified_n = sum(1 for c in audit_result.verified_claims if c.status == "VERIFIED")
            sections.append(
                f"Parallel multi-engine investigation for **{topic}** analyzed {audit_result.total_pages_scraped} pages "
                f"across {len(audit_result.citation_index)} distinct sources in **{elapsed_ms:.1f} ms**. "
                f"**{verified_n}** claims achieved multi-domain consensus."
            )
        else:
            sections.append(
                f"**No sources could be retrieved for {topic}.** The search step returned no reachable results, "
                f"so no claims were gathered and no confidence score could be computed."
            )

        sections.append("\n## Verified Core Findings & Audit Trail\n")
        if audit_result.verified_claims:
            for idx, claim in enumerate(audit_result.verified_claims, start=1):
                cite_tags = [
                    f"[[{url_to_citation[u]}]]({u})" for u in claim.supporting_urls if u in url_to_citation
                ]
                cite_str = " ".join(cite_tags) if cite_tags else "[Source Index]"
                domains_str = ", ".join(claim.supporting_domains) if claim.supporting_domains else "none"
                sections.append(
                    f"### {idx}. {claim.claim_text[:95]}{'...' if len(claim.claim_text) > 95 else ''}\n"
                    f"- **Status:** `{claim.status}` (Confidence: `{int(claim.confidence_score * 100)}%` | Domains: `{domains_str}`)\n"
                    f"- **Excerpt:** \"{claim.claim_text}\"\n"
                    f"- **Verified Sources:** {cite_str}\n"
                )
        else:
            sections.append("No automated claim extractions met threshold limits.")

        sections.append("## Multi-Vector Deep Insights\n")
        dim_map: Dict[str, List[ScrapedPage]] = {}
        for p in pages:
            dim_map.setdefault(p.dimension, []).append(p)

        for dim, dim_pages in dim_map.items():
            sections.append(f"### Dimension: {dim.capitalize()}\n")
            for p in dim_pages:
                cnum = url_to_citation.get(p.url, 0)
                c_link = f"[[{cnum}]]({p.url})" if cnum else ""
                cache_tag = " ⚡cached" if p.from_cache else ""
                sections.append(f"#### [{p.title}]({p.url}) {c_link}")
                sections.append(f"*{p.word_count} words analyzed{cache_tag}.*\n")
                if p.content_markdown:
                    snippet = p.content_markdown[:360].replace("\n", " ")
                    sections.append(f"> {snippet}...\n")

        if audit_result.flagged_hallucinations:
            sections.append("## Flagged Assertions & Potential Hallucinations\n")
            for flag in audit_result.flagged_hallucinations:
                sections.append(f"- {flag}")
            sections.append("")

        sections.append("## Primary Citation Index\n")
        if audit_result.citation_index:
            for c_idx, c_url in audit_result.citation_index.items():
                sections.append(f"{c_idx}. [{c_url}]({c_url})")
        else:
            sections.append("No active citations recorded.")

        final_md = "\n\n".join(sections)
        html_doc = self._render_html(topic, now_str, audit_result, elapsed_ms, cache_hits)

        return ResearchReport(
            topic=topic,
            markdown_content=final_md,
            confidence_score=audit_result.overall_confidence,
            verified_claim_count=len(audit_result.verified_claims),
            citation_count=len(audit_result.citation_index),
            generated_at=now_str,
            elapsed_ms=round(elapsed_ms, 2),
            cache_hits=cache_hits,
            has_evidence=audit_result.has_evidence,
            html_content=html_doc,
        )

    @staticmethod
    def _render_html(
        topic: str,
        now_str: str,
        audit_result: AuditResult,
        elapsed_ms: float,
        cache_hits: int,
    ) -> str:
        safe_topic = html.escape(topic.title())
        score = f"{audit_result.overall_confidence}%" if audit_result.has_evidence else "N/A"
        rows = []
        for vc in audit_result.verified_claims:
            badge_color = {
                "VERIFIED": "#10b981",
                "SINGLE_SOURCE": "#f59e0b",
                "CONTRADICTED": "#ef4444",
            }.get(vc.status, "#64748b")
            links = " ".join(
                f'<a href="{html.escape(u)}" target="_blank" style="color:#60a5fa">source</a>'
                for u in vc.supporting_urls[:3]
            )
            rows.append(
                f"<div class='card'>"
                f"<span class='badge' style='background:{badge_color}'>{html.escape(vc.status)} · {int(vc.confidence_score*100)}%</span>"
                f"<p>{html.escape(vc.claim_text)}</p>"
                f"<div class='meta'>Domains: {html.escape(', '.join(vc.supporting_domains) or 'none')} | {links}</div>"
                f"</div>"
            )
        cites = "".join(
            f"<li><a href='{html.escape(u)}' target='_blank'>{html.escape(u)}</a></li>"
            for u in audit_result.citation_index.values()
        )
        return (
            "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>"
            f"<title>{safe_topic} — LIGHT-LPCA Turbo Report</title>"
            "<style>body{font-family:system-ui,sans-serif;background:#0a0a0f;color:#e2e8f0;max-width:960px;margin:2rem auto;padding:0 1.25rem;}"
            ".hdr{border:1px solid #1e293b;background:#111827;padding:1.5rem;border-radius:14px;margin-bottom:1.5rem;}"
            ".grid{display:grid;grid-template-columns:repeat(4,1fr);gap:1rem;margin-top:1rem;}"
            ".stat{background:#0f172a;padding:.85rem;border-radius:10px;border:1px solid #1e293b;}"
            ".card{background:#111827;border:1px solid #1e293b;padding:1rem;border-radius:12px;margin-bottom:.85rem;}"
            ".badge{display:inline-block;padding:.2rem .55rem;border-radius:999px;font-size:.75rem;font-weight:700;color:#050505;margin-bottom:.5rem;}"
            ".meta{font-size:.82rem;color:#94a3b8;}a{color:#38bdf8;}</style></head><body>"
            f"<div class='hdr'><h1>⚡ {safe_topic}</h1>"
            f"<div class='meta'>LIGHT-LPCA Turbo v2.0 • {html.escape(now_str)}</div>"
            "<div class='grid'>"
            f"<div class='stat'><div class='meta'>Confidence</div><b>{score}</b></div>"
            f"<div class='stat'><div class='meta'>Latency</div><b>{elapsed_ms:.1f} ms</b></div>"
            f"<div class='stat'><div class='meta'>Claims</div><b>{len(audit_result.verified_claims)}</b></div>"
            f"<div class='stat'><div class='meta'>Cache Hits</div><b>{cache_hits}</b></div>"
            "</div></div>"
            f"<h2>Verified Claims</h2>{''.join(rows) or '<p>No claims verified.</p>'}"
            f"<h2>Citations</h2><ol>{cites}</ol></body></html>"
        )
